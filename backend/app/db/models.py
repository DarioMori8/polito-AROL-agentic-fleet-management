from enum import Enum
from datetime import datetime, timezone
from uuid import uuid4
import sqlalchemy as sa
from sqlmodel import SQLModel, Field


class MachineStatus(str, Enum):
    ONLINE = "online"
    OFFLINE = "offline"
    MAINTENANCE = "maintenance"


class DocumentType(str, Enum):
    MANUAL = "manual"
    CONTRACT = "contract"
    WARRANTY = "warranty"
    REVISION = "revision"
    PURCHASE = "purchase"

def _enum_values(enum_cls: type[Enum]) -> list[str]:
    return [e.value for e in enum_cls]

class Machine(SQLModel, table=True):
    __tablename__ = "machines"

    id: str = Field(primary_key=True)
    name: str
    model: str
    serial_number: str
    status: MachineStatus = Field(
        sa_column=sa.Column(sa.Enum(MachineStatus, values_callable=_enum_values), nullable=False)
    )    
    location: str


class Document(SQLModel, table=True):
    __tablename__ = "documents"

    # File identity — UUID generated by us, not an autoincrement int:
    id: str = Field(default_factory=lambda: str(uuid4()), primary_key=True)

    # File block
    filename: str                      # original name, for display only
    storage_path: str                  # where the bytes live on disk (uuid-named)
    content_type: str                  # MIME, e.g. "application/pdf"
    size: int                          # bytes
    uploaded_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)  # UTC, not local time
    )

    # Category — the discriminant; indexed because we filter on it constantly
    # (and it will drive which agent gets notified).
    document_type: DocumentType = Field(
        sa_column=sa.Column(
            sa.Enum(DocumentType, values_callable=_enum_values), nullable=False, index=True
        )
    )
    # Links — both optional. machine_id is a real FK (internal); order_id is a
    # soft reference to the ERP (external system, cannot be a FK).
    machine_id: str | None = Field(
        default=None, foreign_key="machines.id", ondelete="RESTRICT", index=True
    )
    order_id: str | None = Field(default=None)

    # Domain metadata
    title: str | None = Field(default=None)
    language: str | None = Field(default=None)