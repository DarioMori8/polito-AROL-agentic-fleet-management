import React, { useEffect, useState } from 'react';
import { useParams, useNavigate, useSearchParams } from 'react-router';
import LandingQR from './LandingQR';
import { useAuth } from '../context/AuthContext';

/**
 * LandingResolver Component (Wrapper of LandingQR, only for logic)
 * Simple intermediate route component to extract parameters and render LandingQR
 * Also handle automatic guest login (when scanning a QR code)
 */
export default function LandingResolver() {
    const { id } = useParams();
    const navigate = useNavigate();
    const [searchParams] = useSearchParams()
    const { isAuthenticated, loginAsGuest } = useAuth()
    const [guestLoginDone, setGuestLoginDone] = useState(false)

    // If QR params are present, we start in "pending" state to avoid rendering
    // LandingQR with isAuthenticated=false before loginAsGuest() completes.
    const hasQrParams = !!(searchParams.get('u') && searchParams.get('k'))
    const [guestLoginPending, setGuestLoginPending] = useState(hasQrParams)

    // Auto login as guest when the page is reached by scanning a machine QR code.
    // The QR URL carries ?u=<email>&k=<password> (generated by backend/app/db/guest_accounts.py).
    useEffect(() => {
        const guestEmail = searchParams.get('u')
        const guestPassword = searchParams.get('k')
        if (!guestEmail || !guestPassword || isAuthenticated || guestLoginDone) {
            setGuestLoginPending(false)
            return;
        }
        loginAsGuest(guestEmail, guestPassword).then(({ ok }) => {
            setGuestLoginDone(true)
            setGuestLoginPending(false)
            if (!ok) console.warn('LandingResolver: guest credentials rejected by the server.')
        })
    }, [searchParams, isAuthenticated, guestLoginDone, loginAsGuest])

    const handleScanSuccess = (machineId) => {
        // Navigate directly to the conversational workspace upon success
        navigate(`/workspace/${machineId}`);
    };

    const handleNavigateToFleet = () => {
        navigate('/scanner');
    };

    // Block render until guest auto-login completes to avoid a flash of 401 UI.
    if (guestLoginPending) {
        return (
            <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', height: '100vh' }}>
                <span>Loading…</span>
            </div>
        );
    }

    return (
        <LandingQR
            machineIdFromRoute={id}
            onScanSuccess={handleScanSuccess}
            onNavigateToFleet={handleNavigateToFleet}
        />
    );
}